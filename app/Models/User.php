<?php

namespace App\Models;

/*
|--------------------------------------------------------------------------
| LARAVEL
|--------------------------------------------------------------------------
*/

use Illuminate\Database\Eloquent\Factories\HasFactory;

use Illuminate\Foundation\Auth\User
    as Authenticatable;

use Illuminate\Notifications\Notifiable;

/*
|--------------------------------------------------------------------------
| SANCTUM
|--------------------------------------------------------------------------
*/

use Laravel\Sanctum\HasApiTokens;

class User extends Authenticatable


{
    /*
    |--------------------------------------------------------------------------
    | TRAITS
    |--------------------------------------------------------------------------
    */

    use HasApiTokens,
        HasFactory,
        Notifiable;

    /*
    |--------------------------------------------------------------------------
    | FILLABLE
    |--------------------------------------------------------------------------
    */

    protected $fillable = [

        'name',

        'email',

        'password',

        'phone',

        'address',

        'avatar',
    ];

    /*
    |--------------------------------------------------------------------------
    | HIDDEN
    |--------------------------------------------------------------------------
    */

    protected $hidden = [

        'password',

        'remember_token',
    ];

    /*
    |--------------------------------------------------------------------------
    | CASTS
    |--------------------------------------------------------------------------
    */

    protected $casts = [

        'email_verified_at'
            => 'datetime',
    ];


}